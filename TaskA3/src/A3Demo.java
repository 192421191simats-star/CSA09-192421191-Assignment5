import java.sql.ResultSet;
import java.sql.Statement;
import java.util.List;
import model.Course;
import model.Marks;
import model.Student;

/** Task A3 - the duplicated classes and the generic DAO, run against the test database. */
public class A3Demo {
    public static void main(String[] args) throws Exception {
        try (Connection con = Db.open()) {
            try (Statement s = con.createStatement()) { s.executeUpdate("DELETE FROM marks"); s.executeUpdate("DELETE FROM student"); s.executeUpdate("DELETE FROM course"); }
            String url = Db.url(), user = Db.props().getProperty("user"), pwd = Db.props().getProperty("password");

            System.out.println("=== (1) The project as found: StudentDB / CourseDB / MarksDB (each repeats open-build-execute-map-close) ===");
            new before.StudentDB(url, user, pwd).add(new Student("192311001", "Arun Kumar", "CSE", 2, "arun.1001@saveetha.ac.in"));
            new before.CourseDB(url, user, pwd).add(new Course("CSA09", "Programming in Java", 4));
            new before.MarksDB(url, user, pwd).add(new Marks(new Marks.Key("192311001", "CSA09"), 88));
            System.out.println("StudentDB.find  -> " + new before.StudentDB(url, user, pwd).find("192311001"));
            System.out.println("CourseDB.find   -> " + new before.CourseDB(url, user, pwd).find("CSA09"));
            System.out.println("MarksDB.find    -> " + new before.MarksDB(url, user, pwd).find("192311001", "CSA09"));
            try { new before.StudentDB(url, user, pwd).add(new Student("192311002", "D'Souza Priya", "ECE", 1, "p@x.in")); }
            catch (Exception e) { System.out.println("StudentDB.add(\"D'Souza Priya\") -> " + e.getClass().getSimpleName() + ": " + e.getMessage().replaceAll("\\s+", " ") + "   <- string-built SQL breaks on an apostrophe"); }

            System.out.println();
            System.out.println("=== (2) Generic Dao<T, K> - one JdbcDao, three small subclasses ===");
            ConnectionSource src = ConnectionSource.single(con);
            StudentDao students = new StudentDao(src);
            CourseDao courses = new CourseDao(src);
            MarksDao marks = new MarksDao(src);
            System.out.println("SQL generated by StudentDao from its column mapping:");
            System.out.println(students.sqlSummary());
            students.insert(new Student("192311002", "D'Souza Priya", "ECE", 1, "priya.1002@saveetha.ac.in"));
            students.insert(new Student("192311003", "Divya R", "CSE", 3, "divya.1003@saveetha.ac.in"));
            courses.insert(new Course("CSA10", "Data Structures", 3));
            marks.insert(new Marks(new Marks.Key("192311002", "CSA09"), 91));
            marks.insert(new Marks(new Marks.Key("192311003", "CSA10"), 76));
            System.out.println("insert x2 (one name has an apostrophe - bound as a parameter, no problem)");
            System.out.println("findById(192311002)      -> " + students.findById("192311002").orElse(null));
            System.out.println("findById(999999999)      -> " + students.findById("999999999").map(Object::toString).orElse("Optional.empty"));
            System.out.println("findAll()                -> " + students.findAll().size() + " students: " + students.findAll().stream().map(Student::regNo).toList());
            System.out.println("findByDept(CSE)          -> " + students.findByDept("CSE").stream().map(Student::name).toList());
            System.out.println("update(Divya -> year 4)  -> " + students.update(new Student("192311003", "Divya R", "CSE", 4, "divya.r@saveetha.ac.in")) + " ; now " + students.findById("192311003").orElse(null));
            System.out.println("update(unknown reg_no)   -> " + students.update(new Student("999999999", "Nobody", "CSE", 1, "n@x.in")));
            System.out.println("CourseDao.findAll()      -> " + courses.findAll());
            System.out.println("MarksDao.findById(key)   -> " + marks.findById(new Marks.Key("192311002", "CSA09")).orElse(null));
            System.out.println("MarksDao.delete(key)     -> " + marks.delete(new Marks.Key("192311003", "CSA10")) + " ; marks left " + marks.findAll().size());
            System.out.println("delete(192311003)        -> " + students.delete("192311003") + " ; delete again -> " + students.delete("192311003"));

            System.out.println();
            System.out.println("=== (3) A3.3 Student object <-> student table (mapping vs the live table, via DatabaseMetaData) ===");
            DatabaseMetaData md = con.getMetaData();
            String pk = "";
            try (ResultSet rs = md.getPrimaryKeys(null, null, "student")) { while (rs.next()) pk = rs.getString("COLUMN_NAME"); }
            String[] fields = {"regNo : String", "name : String", "dept : String", "year : int", "email : String"};
            System.out.printf("%-18s %-10s %-14s %-9s %s%n", "Student field", "column", "SQL type", "nullable", "key");
            int i = 0;
            try (ResultSet rs = md.getColumns(null, null, "student", "%")) {
                while (rs.next()) {
                    String col = rs.getString("COLUMN_NAME");
                    String tn = rs.getString("TYPE_NAME");
                    String type = tn + (rs.getString("COLUMN_SIZE") == null || tn.startsWith("int") ? "" : "(" + rs.getString("COLUMN_SIZE") + ")");
                    System.out.printf("%-18s %-10s %-14s %-9s %s%n", i < fields.length ? fields[i] : "?", col, type, rs.getString("IS_NULLABLE"), col.equals(pk) ? "PRIMARY KEY" : "");
                    i++;
                }
            }
            List<String> mapped = students.columns().stream().map(c -> c.name() + (c.key() ? "*" : "")).toList();
            System.out.println("StudentDao mapping (* = key): " + mapped);
        }
    }
}
